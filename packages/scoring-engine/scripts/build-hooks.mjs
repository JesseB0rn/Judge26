#!/usr/bin/env node
// Bundles the engine as CommonJS for PocketBase's embedded JS VM (goja), so the
// backend validates and evaluates rulesets with exactly the same code as the
// frontend. Output is generated (git-ignored): apps/backend/hooks/lib/scoring-engine.js
import { build } from 'esbuild'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outfile = join(root, '../../apps/backend/hooks/lib/scoring-engine.js')

await build({
  entryPoints: [join(root, 'src/index.ts')],
  outfile,
  bundle: true,
  format: 'cjs',
  platform: 'neutral',
  // goja supports ES2015+ but not all newer syntax (e.g. optional chaining).
  target: 'es2017',
  banner: { js: '// GENERATED by packages/scoring-engine/scripts/build-hooks.mjs. Do not edit.' },
  logLevel: 'warning',
})
console.log(`Built ${outfile}`)
