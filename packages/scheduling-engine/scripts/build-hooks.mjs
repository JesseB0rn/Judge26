#!/usr/bin/env node
// Bundles the engine as CommonJS for PocketBase's embedded JS VM (see
// packages/scheduling-engine/scripts/build-hooks.mjs). Output is generated
// (git-ignored): apps/backend/hooks/lib/scheduling-engine.js
import { build } from 'esbuild'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const outfile = join(root, '../../apps/backend/hooks/lib/scheduling-engine.js')

await build({
  entryPoints: [join(root, 'src/index.ts')],
  outfile,
  bundle: true,
  format: 'cjs',
  platform: 'neutral',
  target: 'es2017',
  banner: {
    js: '// GENERATED by packages/scheduling-engine/scripts/build-hooks.mjs. Do not edit.',
  },
  logLevel: 'warning',
})
console.log(`Built ${outfile}`)
